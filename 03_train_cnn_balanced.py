
"""Train a CNN for image-level parking occupancy classification.

The script loads preprocessed TFRecord datasets, balances the training
set using data augmentation, trains a convolutional neural network,
and evaluates the best checkpoint on the held-out test set.

Labels:
    0: Less than 80% of annotated parking spaces are occupied.
    1: At least 80% of annotated parking spaces are occupied.

Expected TFRecord files:
    train.tfrecord
    valid.tfrecord
    test.tfrecord

Outputs:
    best_balanced_model.keras
    balanced_cnn_confusion_matrix.png
    balanced_cnn_test_results.json
"""

import json
import random
from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np
import tensorflow as tf

from sklearn.metrics import ConfusionMatrixDisplay, confusion_matrix
from tensorflow import keras
from tensorflow.keras import layers
from tensorflow.keras.losses import BinaryFocalCrossentropy


# ---------------------------------------------------------------------
# Configuration and reproducibility
# ---------------------------------------------------------------------

SEED = 42

# Set random seeds for Python, NumPy, and TensorFlow.
# This improves reproducibility but does not guarantee identical results
# across different hardware, software versions, or execution environments.
keras.utils.set_random_seed(SEED)

# Request deterministic TensorFlow operations where supported.
# This can affect performance or compatibility in some environments.
tf.config.experimental.enable_op_determinism()

# Directory containing TFRecord files generated by the preprocessing
# pipeline. Update this path when running outside Kaggle.
DATASET_DIR = Path("/kaggle/input/datasets/hajar20/my-data")

# Directory for model checkpoints, plots, and evaluation results.
OUTPUT_DIR = Path("/kaggle/working")
OUTPUT_DIR.mkdir(parents=True, exist_ok=True)

# Input images are RGB tensors resized and normalized during preprocessing.
IMAGE_SHAPE = (128, 128, 3)

# Training configuration.
BATCH_SIZE = 32
EPOCHS = 20
AUTOTUNE = tf.data.AUTOTUNE


# ---------------------------------------------------------------------
# TFRecord loading and parsing
# ---------------------------------------------------------------------

def load_tfrecord_dataset(filename):
    """Load a TFRecord file and parse its serialized examples.

    Each TFRecord example is expected to contain:
        - image: A serialized float32 image tensor.
        - label: An integer binary-classification label (0 or 1).

    Args:
        filename: Name of the TFRecord file inside DATASET_DIR.

    Returns:
        A tf.data.Dataset yielding (image, label) pairs.

    Raises:
        FileNotFoundError: If the specified TFRecord file does not exist.
    """
    filepath = DATASET_DIR / filename

    if not filepath.is_file():
        raise FileNotFoundError(
            f"TFRecord file not found: {filepath}"
        )

    # Describe the features stored in each serialized example.
    feature_description = {
        "image": tf.io.FixedLenFeature([], tf.string),
        "label": tf.io.FixedLenFeature([], tf.int64),
    }

    def parse_example(example_proto):
        """Deserialize one TFRecord example into an image and label."""
        parsed = tf.io.parse_single_example(
            example_proto,
            feature_description,
        )

        # Restore the serialized image tensor and enforce its shape.
        image = tf.io.parse_tensor(
            parsed["image"],
            out_type=tf.float32,
        )
        image = tf.ensure_shape(image, IMAGE_SHAPE)

        # Convert the stored int64 label to int32.
        label = tf.cast(parsed["label"], tf.int32)

        return image, label

    # Read the TFRecord file and parse records in parallel.
    dataset = tf.data.TFRecordDataset(str(filepath))
    dataset = dataset.map(
        parse_example,
        num_parallel_calls=AUTOTUNE,
    )

    return dataset


# ---------------------------------------------------------------------
# Dataset inspection and validation
# ---------------------------------------------------------------------

def inspect_dataset(dataset, name):
    """Count examples, validate labels, and report dataset properties.

    Args:
        dataset: A tf.data.Dataset yielding (image, label) pairs.
        name: Human-readable name of the dataset split.

    Returns:
        A dictionary containing the total number of examples and
        the number of examples belonging to each class.

    Raises:
        ValueError: If the dataset is empty or contains invalid labels.
    """
    total = 0
    class_counts = {0: 0, 1: 0}
    first_batch_shape = None

    # Iterate in batches to inspect labels and count examples.
    for images, labels in dataset.batch(BATCH_SIZE):
        if first_batch_shape is None:
            first_batch_shape = tuple(images.shape)

        labels_np = labels.numpy()

        # Reject labels outside the expected binary classes.
        invalid_labels = set(np.unique(labels_np)) - {0, 1}

        if invalid_labels:
            raise ValueError(
                f"{name} contains invalid labels: {invalid_labels}"
            )

        total += len(labels_np)
        class_counts[0] += int(np.sum(labels_np == 0))
        class_counts[1] += int(np.sum(labels_np == 1))

    if total == 0:
        raise ValueError(f"{name} dataset is empty.")

    print(f"\n{name} dataset")
    print(f"  First batch shape: {first_batch_shape}")
    print(f"  Total examples: {total}")
    print(f"  Class 0 (<80% occupied): {class_counts[0]}")
    print(f"  Class 1 (>=80% occupied): {class_counts[1]}")

    return {
        "total": total,
        "class_counts": class_counts,
    }


# Load the training, validation, and test datasets.
train_dataset = load_tfrecord_dataset("train.tfrecord")
valid_dataset = load_tfrecord_dataset("valid.tfrecord")
test_dataset = load_tfrecord_dataset("test.tfrecord")

# Inspect the original splits before training.
train_stats = inspect_dataset(train_dataset, "Training")
valid_stats = inspect_dataset(valid_dataset, "Validation")
test_stats = inspect_dataset(test_dataset, "Test")


# ---------------------------------------------------------------------
# Training-set balancing with data augmentation
# ---------------------------------------------------------------------

def augment_minority_class(dataset, seed=SEED):
    """Balance a binary dataset by augmenting its minority class.

    All original examples are retained. Additional examples are generated
    by randomly transforming images from the minority class.

    IMPORTANT:
        Apply this function only to the training dataset.
        Validation and test datasets must remain unchanged.

    Augmentations:
        - Random horizontal flip
        - Random vertical flip
        - Random brightness adjustment
        - Random contrast adjustment

    Args:
        dataset: Unbatched dataset yielding (image, label) pairs.
        seed: Seed used for shuffling the resulting dataset.

    Returns:
        A shuffled dataset with equal numbers of class 0 and class 1.
    """

    def augment_image(image, label):
        """Apply random image transformations while preserving the label."""

        # Randomly flip the image horizontally and vertically.
        image = tf.image.random_flip_left_right(image)
        image = tf.image.random_flip_up_down(image)

        # Apply small random brightness and contrast adjustments.
        image = tf.image.random_brightness(
            image,
            max_delta=0.1,
        )
        image = tf.image.random_contrast(
            image,
            lower=0.9,
            upper=1.1,
        )

        # Keep normalized pixel values within the range [0, 1].
        image = tf.clip_by_value(image, 0.0, 1.0)

        # The augmentation changes the image, not its class label.
        return image, label

    # Count the examples in each class.
    class_counts = {0: 0, 1: 0}

    for _, labels in dataset.batch(1024):
        labels_np = labels.numpy()

        # Check that the dataset contains only binary labels.
        invalid_labels = set(np.unique(labels_np)) - {0, 1}

        if invalid_labels:
            raise ValueError(
                f"Expected binary labels 0 and 1; found {invalid_labels}"
            )

        class_counts[0] += int(np.sum(labels_np == 0))
        class_counts[1] += int(np.sum(labels_np == 1))

    count_0 = class_counts[0]
    count_1 = class_counts[1]

    # Both classes must be present for binary class balancing.
    if count_0 == 0 or count_1 == 0:
        raise ValueError(
            f"Both classes must be present. Counts: {class_counts}"
        )

    # If the classes are already balanced, only shuffle the dataset.
    if count_0 == count_1:
        print("Dataset is already balanced.")

        return dataset.shuffle(
            buffer_size=10000,
            seed=seed,
            reshuffle_each_iteration=True,
        )

    # Create separate datasets for the two classes.
    class_0_dataset = dataset.filter(
        lambda image, label: tf.equal(label, 0)
    )
    class_1_dataset = dataset.filter(
        lambda image, label: tf.equal(label, 1)
    )

    # Identify the minority and majority classes.
    if count_0 < count_1:
        minority_dataset = class_0_dataset
        majority_dataset = class_1_dataset
        minority_count = count_0
        majority_count = count_1
        minority_label = 0
    else:
        minority_dataset = class_1_dataset
        majority_dataset = class_0_dataset
        minority_count = count_1
        majority_count = count_0
        minority_label = 1

    # Generate enough augmented examples to match the majority class.
    extra_needed = majority_count - minority_count

    # Repeat minority examples, apply random transformations, and take
    # exactly the required number of additional examples.
    augmented_minority = (
        minority_dataset
        .repeat()
        .map(
            augment_image,
            num_parallel_calls=AUTOTUNE,
        )
        .take(extra_needed)
    )

    # Keep all original minority examples and append the augmented ones.
    balanced_minority = minority_dataset.concatenate(
        augmented_minority
    )

    # Combine the balanced minority class with the unchanged majority class.
    balanced_dataset = balanced_minority.concatenate(
        majority_dataset
    )

    # Shuffle the resulting dataset so batches contain mixed classes.
    balanced_dataset = balanced_dataset.shuffle(
        buffer_size=10000,
        seed=seed,
        reshuffle_each_iteration=True,
    )

    # Report the expected balancing operation.
    print(f"Original class counts: {class_counts}")
    print(f"Minority class: {minority_label}")
    print(f"Additional augmented examples: {extra_needed}")
    print(f"Expected balanced class counts: {majority_count} per class")
    print(f"Expected balanced total: {2 * majority_count}")

    return balanced_dataset


# Balance only the training dataset.
balanced_train_dataset = augment_minority_class(train_dataset)

# Inspect the resulting dataset to verify its class distribution.
balanced_stats = inspect_dataset(
    balanced_train_dataset,
    "Balanced training",
)

balanced_counts = balanced_stats["class_counts"]
balanced_total = balanced_stats["total"]

print(f"Balanced class distribution: {balanced_counts}")
print(f"Total balanced examples: {balanced_total}")

# Stop execution if the classes are not balanced as expected.
assert balanced_counts[0] == balanced_counts[1], (
    f"Classes are not balanced: {balanced_counts}"
)


# ---------------------------------------------------------------------
# Batch and prefetch datasets
# ---------------------------------------------------------------------

# Batch the balanced training data.
# Repeat the training dataset so it does not run out of examples.
# Explicit steps_per_epoch below limit each epoch to one pass worth
# of batches through the balanced dataset.
balanced_train_data = (
    balanced_train_dataset
    .batch(BATCH_SIZE, drop_remainder=False)
    .repeat()
    .prefetch(AUTOTUNE)
)

# Keep validation and test datasets finite and unaugmented.
valid_data = (
    valid_dataset
    .batch(BATCH_SIZE, drop_remainder=False)
    .prefetch(AUTOTUNE)
)

test_data = (
    test_dataset
    .batch(BATCH_SIZE, drop_remainder=False)
    .prefetch(AUTOTUNE)
)

# Calculate batch counts, including any final partial batch.
train_batches = (
    balanced_stats["total"] + BATCH_SIZE - 1
) // BATCH_SIZE

valid_batches = (
    valid_stats["total"] + BATCH_SIZE - 1
) // BATCH_SIZE

test_batches = (
    test_stats["total"] + BATCH_SIZE - 1
) // BATCH_SIZE

print(f"Training steps per epoch: {train_batches}")
print(f"Validation batches: {valid_batches}")
print(f"Test batches: {test_batches}")


# ---------------------------------------------------------------------
# Define the convolutional neural network (CNN)
# ---------------------------------------------------------------------

model = keras.Sequential(
    [
        # Input: normalized RGB images of shape 128 x 128 x 3.
        keras.Input(shape=IMAGE_SHAPE),

        # First convolutional block learns low-level visual features.
        layers.Conv2D(
            filters=32,
            kernel_size=(3, 3),
            activation="relu",
        ),
        layers.BatchNormalization(),
        layers.MaxPooling2D(pool_size=(2, 2)),
        layers.Dropout(0.2),

        # Second convolutional block learns more complex features.
        layers.Conv2D(
            filters=64,
            kernel_size=(3, 3),
            activation="relu",
        ),
        layers.BatchNormalization(),
        layers.MaxPooling2D(pool_size=(2, 2)),
        layers.Dropout(0.2),

        # Flatten feature maps before the dense classification layers.
        layers.Flatten(),
        layers.Dense(128, activation="relu"),

        # Predict the probability that the image belongs to class 1.
        layers.Dense(1, activation="sigmoid"),
    ],
    name="parking_occupancy_cnn",
)

# Display the architecture, output shapes, and parameter counts.
model.summary()


# ---------------------------------------------------------------------
# Compile the CNN
# ---------------------------------------------------------------------

model.compile(
    # AdamW uses adaptive optimization with weight decay.
    optimizer=keras.optimizers.AdamW(
        learning_rate=0.0002,
        weight_decay=1e-5,
        global_clipnorm=5.0,
    ),

    # Focal loss emphasizes difficult examples during training.
    loss=BinaryFocalCrossentropy(gamma=2.0),

    # Track threshold-based metrics and ranking metrics.
    metrics=[
        keras.metrics.BinaryAccuracy(name="accuracy"),
        keras.metrics.Precision(name="precision"),
        keras.metrics.Recall(name="recall"),
        keras.metrics.AUC(curve="ROC", name="auc_roc"),
        keras.metrics.AUC(curve="PR", name="auc_pr"),
    ],
)


# ---------------------------------------------------------------------
# Configure model checkpoints and training callbacks
# ---------------------------------------------------------------------

# Save the best model checkpoint in the output directory.
BEST_MODEL_PATH = OUTPUT_DIR / "best_balanced_model.keras"

callbacks = [
    # Stop training if validation PR-AUC no longer improves.
    # Restore the best epoch's weights in the in-memory model.
    keras.callbacks.EarlyStopping(
        monitor="val_auc_pr",
        mode="max",
        patience=5,
        restore_best_weights=True,
        verbose=1,
    ),

    # Reduce the learning rate when validation PR-AUC plateaus.
    keras.callbacks.ReduceLROnPlateau(
        monitor="val_auc_pr",
        mode="max",
        factor=0.5,
        patience=3,
        min_lr=1e-6,
        verbose=1,
    ),

    # Save the checkpoint with the highest validation PR-AUC.
    keras.callbacks.ModelCheckpoint(
        filepath=str(BEST_MODEL_PATH),
        monitor="val_auc_pr",
        mode="max",
        save_best_only=True,
        verbose=1,
    ),
]


# ---------------------------------------------------------------------
# Train the model
# ---------------------------------------------------------------------

history = model.fit(
    balanced_train_data,
    validation_data=valid_data,
    epochs=EPOCHS,
    steps_per_epoch=train_batches,
    validation_steps=valid_batches,
    callbacks=callbacks,
    verbose=1,
)


# ---------------------------------------------------------------------
# Identify the best epoch and load the saved checkpoint
# ---------------------------------------------------------------------

# Determine the epoch with the highest validation PR-AUC.
best_epoch = int(np.argmax(history.history["val_auc_pr"])) + 1

best_validation_pr_auc = float(
    history.history["val_auc_pr"][best_epoch - 1]
)

print(f"\nBest epoch: {best_epoch}")
print(f"Best validation PR-AUC: {best_validation_pr_auc:.4f}")

# Verify that the expected checkpoint was saved.
if not BEST_MODEL_PATH.is_file():
    raise FileNotFoundError(
        f"Best model checkpoint was not created: {BEST_MODEL_PATH}"
    )

# Load the checkpoint selected by validation PR-AUC.
best_model = keras.models.load_model(BEST_MODEL_PATH)


# ---------------------------------------------------------------------
# Evaluate the best checkpoint on the held-out test set
# ---------------------------------------------------------------------

# Evaluate the saved model once on the untouched test dataset.

test_results = best_model.evaluate(
    test_data,
    steps=test_batches,
    return_dict=True,
    verbose=1,
)


print("\nFinal Test Results")

for metric, value in test_results.items():
    print(f"{metric}: {value:.4f}")


# ---------------------------------------------------------------------
# Generate predictions and calculate the confusion matrix
# ---------------------------------------------------------------------

# Collect the true test labels in dataset order.
y_true = np.concatenate(
    [labels.numpy() for _, labels in test_data]
)

# Predict probabilities for the high-occupancy class (class 1).
y_pred_probs = best_model.predict(
    test_data,
    steps=test_batches,
    verbose=1,
).ravel()

# Ensure that every test example has exactly one prediction.
if len(y_true) != len(y_pred_probs):
    raise ValueError(
        "The number of predictions does not match the number "
        f"of test labels: {len(y_pred_probs)} predictions, "
        f"{len(y_true)} labels."
    )

# Convert probabilities to binary predictions using a threshold of 0.5.
y_pred = (y_pred_probs >= 0.5).astype(np.int32)

# Calculate the confusion matrix with a fixed class order:
# [[true negatives, false positives],
#  [false negatives, true positives]]
cm = confusion_matrix(
    y_true,
    y_pred,
    labels=[0, 1],
)

print("\nConfusion Matrix")
print(cm)


# ---------------------------------------------------------------------
# Visualize and save the confusion matrix
# ---------------------------------------------------------------------

cm_display = ConfusionMatrixDisplay(
    confusion_matrix=cm,
    display_labels=["<80% occupied", ">=80% occupied"],
)

cm_display.plot(
    cmap="Blues",
    values_format="d",
)

plt.title("Confusion Matrix — Balanced CNN")
plt.tight_layout()

CONFUSION_MATRIX_PATH = (
    OUTPUT_DIR / "balanced_cnn_confusion_matrix.png"
)

plt.savefig(
    CONFUSION_MATRIX_PATH,
    dpi=300,
    bbox_inches="tight",
)

plt.show()
plt.close()

print(f"\nConfusion matrix saved to: {CONFUSION_MATRIX_PATH}")


# ---------------------------------------------------------------------
# Save test metrics and experiment metadata as JSON
# ---------------------------------------------------------------------

TEST_RESULTS_PATH = OUTPUT_DIR / "balanced_cnn_test_results.json"

# Convert TensorFlow/NumPy metric values to standard Python floats.
test_results_json = {
    metric: float(value)
    for metric, value in test_results.items()
}

# Include the confusion matrix and details needed to interpret results.
test_results_json["confusion_matrix"] = cm.tolist()
test_results_json["confusion_matrix_labels"] = [
    "less_than_80_percent",
    "at_least_80_percent",
]
test_results_json["classification_threshold"] = 0.5

# Record which training epoch achieved the best validation PR-AUC.
test_results_json["best_epoch"] = best_epoch
test_results_json["best_validation_pr_auc"] = best_validation_pr_auc

# Include the dataset sizes and class distributions for traceability.
test_results_json["dataset_summary"] = {
    "original_training_examples": train_stats["total"],
    "balanced_training_examples": balanced_stats["total"],
    "validation_examples": valid_stats["total"],
    "test_examples": test_stats["total"],
    "original_training_class_counts": {
        str(label): count
        for label, count in train_stats["class_counts"].items()
    },
    "balanced_training_class_counts": {
        str(label): count
        for label, count in balanced_stats["class_counts"].items()
    },
    "validation_class_counts": {
        str(label): count
        for label, count in valid_stats["class_counts"].items()
    },
    "test_class_counts": {
        str(label): count
        for label, count in test_stats["class_counts"].items()
    },
}

# Record the main experiment settings.
test_results_json["experiment_config"] = {
    "seed": SEED,
    "image_shape": list(IMAGE_SHAPE),
    "batch_size": BATCH_SIZE,
    "maximum_epochs": EPOCHS,
    "optimizer": "AdamW",
    "learning_rate": 0.0002,
    "weight_decay": 1e-5,
    "global_clipnorm": 5.0,
    "loss": "BinaryFocalCrossentropy",
    "focal_loss_gamma": 2.0,
}

# Write the results in a human-readable JSON format.
with TEST_RESULTS_PATH.open("w", encoding="utf-8") as file:
    json.dump(
        test_results_json,
        file,
        indent=4,
    )

print(f"Test metrics saved to: {TEST_RESULTS_PATH}")
